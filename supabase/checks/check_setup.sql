problems as (
  select 'missing table' as what, t.name
    from expected_tables t
   where not exists (select 1 from pg_class c join pg_namespace n on n.oid = c.relnamespace
                      where n.nspname = 'public' and c.relkind = 'r' and c.relname = t.name)
  union all
  select 'missing function', f.name
    from expected_functions f
   where not exists (select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace
                      where n.nspname = 'public' and p.proname = f.name)
  union all
  select 'row security is off', c.relname
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
   where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity
)
select what, name from problems
union all
select 'Everything is in place', (select count(*) from expected_tables)::text || ' tables and ' || (select count(*) from expected_functions)::text || ' functions checked'
 where not exists (select 1 from problems)
order by 1, 2;
